/**
 * Generates docs/TOKENS.md: every design token and Sass helper available to a
 * `.module.scss` file, read from src/styles so the list cannot drift.
 * Run: `pnpm generate:tokens` (also on postinstall).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const read = (file: string) =>
  readFileSync(path.join(root, 'src/styles', file), 'utf8');

const tokenNames = (source: string): string[] => [
  ...new Set(
    [...source.matchAll(/--([a-z0-9-]+)\s*:/gi)].map((m) => `--${m[1]}`),
  ),
];
const scssMixins = (source: string): string[] =>
  [...source.matchAll(/@mixin\s+([a-z0-9-]+)/gi)].map(
    (m) => `@include ${m[1]}`,
  );
const scssFunctions = (source: string): string[] =>
  [...source.matchAll(/@function\s+([a-z0-9-]+)/gi)].map((m) => `${m[1]}()`);
const scssVariables = (source: string): string[] => [
  ...new Set(
    [...source.matchAll(/^\$([a-z0-9-]+)\s*:/gim)].map((m) => `$${m[1]}`),
  ),
];

const tokens = read('tokens.scss');
const palette = read('palette.scss');
const helpers = read('helpers.scss');

const groups = [
  {
    title: 'Semantic tokens (src/styles/tokens.scss) — use these in components',
    description:
      'Defined on `:root`, colour tokens redefined for `[data-theme="dark"]` and `prefers-color-scheme: dark`.',
    items: tokenNames(tokens).filter(
      (name) => !tokenNames(palette).includes(name),
    ),
  },
  {
    title: 'Palette (src/styles/palette.scss) — tokens.scss only',
    description:
      'Raw brand scale. Components never reference these; Stylelint fails any `var(--primary-…)` outside tokens.scss.',
    items: tokenNames(palette),
  },
  {
    title: 'Sass helpers (src/styles/helpers.scss) — injected everywhere',
    description:
      '`spacing($factor)` returns `$factor * 0.125rem`. Breakpoint mixins wrap `@media (width <= $bp)`: mobile 768px, tablet 1024px, desktop 1280px, desktop-lg 1600px.',
    items: [
      ...scssFunctions(helpers),
      ...scssMixins(helpers),
      ...scssVariables(helpers),
    ],
  },
];

const lines: string[] = [
  '# Design tokens',
  '',
  '<!-- Generated by scripts/generate-token-docs.ts. Do not edit by hand. -->',
  '',
  'Every `.module.scss` has the Sass helpers injected (breakpoint mixins, `spacing()`), so nothing below needs an import.',
  '',
  '**Rule:** components use semantic tokens (`var(--color-text)`). Palette tokens are allowed only in `src/styles/tokens.scss`. Stylelint enforces both.',
  '',
];
for (const group of groups) {
  lines.push(`## ${group.title}`, '', group.description, '');
  for (const item of group.items) lines.push(`- \`${item}\``);
  lines.push('');
}
writeFileSync(path.join(root, 'docs/TOKENS.md'), `${lines.join('\n')}\n`);
console.log(
  `docs/TOKENS.md written (${groups.reduce((n, g) => n + g.items.length, 0)} entries).`,
);
